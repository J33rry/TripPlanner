import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const GRID_STEP = 1;

const topology = require("world-atlas/land-50m.json");
const land = feature(topology, topology.objects.land);

const bits = [];
const rows = Math.round(180 / GRID_STEP);
for (let i = 0; i < rows; i++) {
  const lat = 90 - GRID_STEP * (i + 0.5);
  const count = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / GRID_STEP));
  for (let j = 0; j < count; j++) {
    const lon = -180 + ((j + 0.5) * 360) / count;
    bits.push(geoContains(land, [lon, lat]) ? 1 : 0);
  }
}

const bytes = new Uint8Array(Math.ceil(bits.length / 8));
bits.forEach((bit, index) => {
  if (bit) bytes[index >> 3] |= 1 << (index & 7);
});

const landCount = bits.reduce((sum, bit) => sum + bit, 0);
const out = `// Generated by scripts/generate-land-mask.mjs from Natural Earth 1:50m land
// (via world-atlas). Do not edit by hand.
export const GRID_STEP = ${GRID_STEP};
export const GRID_POINTS = ${bits.length};
export const LAND_POINTS = ${landCount};
export const LAND_MASK = "${Buffer.from(bytes).toString("base64")}";
`;

writeFileSync(new URL("../lib/landMask.js", import.meta.url), out);
console.log(`Wrote lib/landMask.js: ${landCount} land dots of ${bits.length}`);
